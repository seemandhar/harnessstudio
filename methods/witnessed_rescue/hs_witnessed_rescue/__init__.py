"""witnessed-rescue (hs_witnessed_rescue): SCALE-decoded frozen OpenVLA + event-triggered, depth-grounded,
planner-witnessed grasp rescue (Run X idea x-r1-witnessed-rescue). See controller.py and README.md.

Entry points (cards generated by scripts/make_cards.py from one constant set; params live in the card):
  witnessed-rescue (candidate), witnessed-rescue-respondoff (SCALE-shadow null),
  witnessed-rescue-noplace and witnessed-rescue-analytic (descriptive ablations, never Campaign entries).
"""
from __future__ import annotations

from pathlib import Path

FACTORY = "hs_witnessed_rescue.controller:WitnessedRescue"


def _config(card_name: str):
    from harnessstudio.core.card import config_from_card, load_card
    from harnessstudio.core.method import ModuleRef

    path = Path(__file__).with_name(card_name)
    params = dict(load_card(path)["params"])
    return config_from_card(path, controller=ModuleRef(FACTORY, params))


def config():
    return _config("paper.yaml")


def config_respondoff():
    return _config("paper_respondoff.yaml")


def config_noplace():
    return _config("paper_noplace.yaml")


def config_analytic():
    return _config("paper_analytic.yaml")
