#!/usr/bin/env python3
"""Write task-sharded vla-eval configs for the rtcf development memory and the paired evaluation.

    python3 methods/rtcf/scripts/make_configs.py --suite libero_10 --kind dev  --seed 7   --out methods/rtcf/configs/generated
    python3 methods/rtcf/scripts/make_configs.py --suite libero_10 --kind eval --seed 101 --out ...

dev : init states 10-29 (episode_offset 10, 20 episodes per task; budget decision predeclared in
      runs/rtcf-20261031/protocol/run-order.md before outcomes, match_sequential_resets: true so the scenes are
      those of a stock sequential seed-7 run, critic B3), seed 7 (paper: memory seed 7)
eval: init states 0-9 (10 episodes per task), seeds 101-105 (paper); one whole (task, seed) block per shard, run with
      --case-namespace seed<S> --benchmark-overrides '{"params": {"seed": S}}' and its own --out (critic B7)
Cadence is not in these files: it is the profile (methods/rtcf/configs/pi0fast-libero-hs.yaml, execute_horizon 5).
Every config sets quat_no_antipodal: true (openpi/robosuite axis-angle; vla-eval's default flips rx near the
gripper-down pose and breaks pi0_fast_libero, found in bring-up 2026-10-31) and num_steps_wait 10; horizons come
from vla-eval / the HarnessStudio libero contract (220/280/300/520). `--gpu` is the LIBERO render GPU.
"""
from __future__ import annotations

import argparse
from pathlib import Path

VLA_EVAL = "/home/sejain/research/cvpr27/vla-eval-v0.8.0/configs/benchmarks/libero"
HS = "/home/sejain/research/cvpr27/RoboMetaHarness-claude/harnessstudio"
STOCK = {"libero_10": "10.yaml", "libero_spatial": "spatial.yaml", "libero_object": "object.yaml",
         "libero_goal": "goal.yaml"}

TEMPLATE = """# rtcf {kind}: {suite} task_ids {ids}, {what}, seed {seed}. Generated by methods/rtcf/scripts/make_configs.py.
extends: {vla_eval}/{stock}
server:
  url: "ws://localhost:1"
docker:
  image: ghcr.io/allenai/vla-evaluation-harness/libero:latest
  gpus: "{gpu}"
  user: host
  env:
    - HOME=/tmp
    - LIBERO_CONFIG_PATH=/etc/libero
    - PYTHONPATH=/hs:/hs/methods/rtcf/bench_ext
  volumes:
    - /home/sejain/research/cvpr27/hs2-gpu/libero_config:/etc/libero:ro
    - {hs}:/hs:ro
output_dir: /tmp/rtcf-vla-eval-unused
benchmarks:
  - benchmark: "hs_rtcf_bench:LIBEROSelect"
    subname: {suite}
    episodes_per_task: {episodes}
    params:
      suite: {suite}
      seed: {seed}
      num_steps_wait: 10
      quat_no_antipodal: true
      episode_offset: {offset}
      match_sequential_resets: {msr}
      task_ids: [{ids}]
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--suite", required=True, choices=sorted(STOCK))
    ap.add_argument("--kind", required=True, choices=["dev", "eval"])
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--tasks-per-shard", type=int, default=1)
    ap.add_argument("--dev-first", type=int, default=10, help="first development init state (dev only)")
    ap.add_argument("--dev-count", type=int, default=20, help="development init states per task (dev only)")
    ap.add_argument("--gpu", default="7")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.kind == "dev" and (a.dev_first < 10 or a.dev_first + a.dev_count > 30):
        raise SystemExit("development init states must lie within [10, 29] (run-order.md; eval uses 0-9)")
    offset, episodes = (a.dev_first, a.dev_count) if a.kind == "dev" else (0, 10)
    what = f"init states {offset}-{offset + episodes - 1}"
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for start in range(0, 10, a.tasks_per_shard):
        ids = list(range(start, min(10, start + a.tasks_per_shard)))
        text = TEMPLATE.format(kind=a.kind, suite=a.suite, ids=", ".join(map(str, ids)), what=what, seed=a.seed,
                               vla_eval=VLA_EVAL, stock=STOCK[a.suite], gpu=a.gpu, hs=HS, episodes=episodes,
                               offset=offset, msr="true" if a.kind == "dev" else "false")
        name = f"{a.kind}_{a.suite}_seed{a.seed}_t{'-'.join(map(str, ids))}.yaml"
        (out / name).write_text(text)
        print(out / name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
