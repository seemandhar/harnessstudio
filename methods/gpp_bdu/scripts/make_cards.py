#!/usr/bin/env python3
"""Generate the gpp-bdu cards (hs_gpp_bdu/paper_<entry>.yaml) from the FROZEN hs_gpp v1.1 cards (read-only) plus one
frozen bdu constant set (review proposals-r3-review.json BDU-RC1). Existing hs_gpp / greedy-escape entries are untouched.

    harnessstudio/.venv/bin/python harnessstudio/methods/gpp_bdu/scripts/make_cards.py
"""
from __future__ import annotations

import copy
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parents[1] / "hs_gpp_bdu"
GPP = Path(__file__).resolve().parents[2] / "gpp/hs_gpp"
BDU = {"n": 20, "az": -0.2, "dz": -0.0005, "max_fires": 4, "window": 10, "lift_az": 0.15, "lateral": 0.025}

ENTRIES = {   # name: (parent card, module overrides, bdu mode, description)
    "ge-gpp-bdu": ("ge_gpp_core", {}, "on", "ge-gpp-core + bdu (blocked-descent unload): primary round-3 vehicle."),
    "ge-gpp-bdusham": ("ge_gpp_core", {}, "sham", "ge-gpp-core + bdu lift-only sham (a_z +0.15, a_x = a_y = 0)."),
    "ge-bdu": ("ge_gpp_core", {"h1": "off", "h2": "off"}, "on", "greedy-escape + bdu (gpp modules off): vehicle variant."),
    "ge-bdusham": ("ge_gpp_core", {"h1": "off", "h2": "off"}, "sham", "greedy-escape + bdu lift-only sham."),
    "gpp-bdu": ("gpp_core", {}, "on", "gpp-core + bdu (greedy-escape off; deterministic): vehicle variant."),
    "gpp-bdusham": ("gpp_core", {}, "sham", "gpp-core + bdu lift-only sham."),
}

DISCLOSURES = [
    "New training-free mechanism (bdu; review r3 D1-D4 of proposals-r2-review apply): during a <= 10-step window the "
    "executed action is the policy's own action with a_z replaced by +0.15 (lateral, rotation and gripper native; sham: "
    "a_x = a_y = 0 too). One greedy decode every step; no extra policy call (c = 1.0). analytic_control declared; every "
    "edited step logged (ctx.record bdu phase=edit) and counted (accounting.extra.gpp.bdu_edited_steps).",
    "Trigger (BDU-RC1, frozen a priori; N = 20 chosen in-sample from the 15/20/25 sensitivity): b_k = a_z < -0.2 AND "
    "gripper open AND realized dz > -0.5 mm; fire at 20 consecutive b. Window ends on a policy close (executed natively), "
    ">= 2.5 cm lateral since the fire, or 10 steps; counter reset; <= 4 fires. Exposed greedy successes t1i1, t1i7 "
    "(the trigger cannot separate a productive press in task 1).",
    "Frozen counting rule: every executed action feeds the bdu counter; a GE-window step resets it (not evaluated "
    "inside GE windows); a fire is evaluated only after a step with no active primitive / bdu window / GE window and no "
    "pending H2/H3 fire. A bdu window decodes greedily; a GE window starting at the same step is consumed by it.",
    "Isolation: hs_gpp v1.1 (running screens import it) is imported read-only; hs_gpp_bdu subclasses its controller and "
    "refuses to build unless hs_gpp's files and the gpp-core / ge-gpp-core / greedy-escape fingerprints equal the frozen "
    "values. With bdu off (and before the first bdu fire) requests and actions equal the parent's.",
]


def main() -> None:
    header = "# GENERATED by scripts/make_cards.py (gpp-bdu v1.0); edit the generator, not this file.\n"
    for name, (parent, mods, mode, desc) in ENTRIES.items():
        base = yaml.safe_load((GPP / f"paper_{parent}.yaml").read_text())
        card = copy.deepcopy(base)
        card["name"], card["version"] = name, "1.0"
        card["paper"] = {"id": f"rmh:scalepp-20261102/{name}",
                         "title": "gpp-bdu: frozen gpp v1.1 controller + bdu blocked-descent unload (new training-free "
                                  "mechanism, RoboMetaHarness run scalepp-20261102, proposal idea-r3a), not a reproduction",
                         "venue": "none (internal)", "parent": f"hs_gpp:{parent} v1.1"}
        params = card["params"]
        params["modules"] = {**params["modules"], **mods, "bdu": mode}
        params["bdu"] = dict(BDU)
        card["params"] = params
        card["description"] = desc
        card["disclosures"] = list(base.get("disclosures") or []) + DISCLOSURES
        card["changelog"] = [f"v1.0 (2026-11-02): first implementation (task impl-bdu) under review r3 BDU-RC1..RC5; "
                             f"parent {parent} v1.1 unchanged; frozen before any bdu episode."]
        card["original"] = {"repo": "none (original method)", "commit": "",
                            "reported": "none; predictions in ideation/idea-r3a.json and reviews/proposals-r3-review.json"}
        path = PKG / f"paper_{name.replace('-', '_')}.yaml"
        path.write_text(header + yaml.safe_dump(card, sort_keys=False, width=120))
        print(path)


if __name__ == "__main__":
    main()
