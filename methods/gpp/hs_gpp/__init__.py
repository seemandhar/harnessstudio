"""gpp (hs_gpp): native greedy OpenVLA plus public-proprio scripted primitives - H2 deeper re-close (after the first
empty close before any carry: open, descend <= 3 cm with a contact stop, hand back) and H1 clamp-lift (a settled,
never-lifted clamp about to be released: veto the open, lift <= 6 cm, abort if blocked or custody lost). H3 freeze
nudge and a greedy-escape module are config switches. See controller.py and rules.py.

Entry points (cards generated by scripts/make_cards.py from one frozen constant set):
  gpp-core (candidate), gpp-core-sham (directional sham), gpp-h2 / gpp-h2-sham (time-guard fallback and its sham),
  ge-gpp-core (greedy-escape + gpp-core composition; conditional, review compositions).
Approved proposal runs/scalepp-20261102/ideation/idea-r2b.json; review runs/scalepp-20261102/reviews/proposals-r2-review.json.
"""
from __future__ import annotations

from pathlib import Path

from harnessstudio.core.card import config_from_card, load_card
from harnessstudio.core.method import ModuleRef

FACTORY = "hs_gpp.controller:GppController"


def _config(entry: str):
    path = Path(__file__).with_name(f"paper_{entry}.yaml")
    params = dict(load_card(path)["params"])
    return config_from_card(path, controller=ModuleRef(FACTORY, params))


def config_gpp_core():
    return _config("gpp_core")


def config_gpp_core_sham():
    return _config("gpp_core_sham")


def config_gpp_h2():
    return _config("gpp_h2")


def config_gpp_h2_sham():
    return _config("gpp_h2_sham")


def config_ge_gpp_core():
    return _config("ge_gpp_core")
