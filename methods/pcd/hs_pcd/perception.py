"""Counterfactual-frame clients: the PCD perception service over HTTP, and a deterministic stub for tier 1.

The service (harnessstudio/methods/pcd/service/, its own venv; owned by the perception task) re-derives the
PCD-Mask GroundingDINO path of Koorye/PCD @ 31b027e (GDINO-base 0.25/0.3, SAM2.1-L camera-predictor tracking with
no re-detection, Big-LaMa every step). This module talks to it ONLY through its HTTP API
(service/pcd_perception/server.py docstring):

    GET  /health                                   -> {"ok", "version", "device", "weights", "sam2_C", "sessions"}
    POST /reset {"session", "instruction"}          -> episode summary
    POST /step  {"session", "instruction", "image_npy"}
                -> {"cf_npy", "phase", "targets", "per_target": {name: {mask_present, area_fraction, tracker_none}},
                    "robot_mask_present", "robot_area_fraction", "paste_area_fraction", "inpaint_area_fraction",
                    "cf_differs", "cf_sha256", "timing_ms", "episode": {...}, "calls": {...}}
    POST /close {"session"}

The session token is generated by the method (uuid4), never derived from the case, seed or arm (INVARIANTS 2);
each arm and episode has its own session, so the null's tracker runs on the native trajectory.
"""
from __future__ import annotations

import base64
import io
import json
import urllib.request
import uuid
from typing import Optional

import numpy as np


def _npy_b64(arr: np.ndarray) -> str:
    buf = io.BytesIO()
    np.save(buf, np.ascontiguousarray(arr, dtype=np.uint8), allow_pickle=False)
    return base64.b64encode(buf.getvalue()).decode()


def _from_npy_b64(text: str) -> np.ndarray:
    return np.load(io.BytesIO(base64.b64decode(text)), allow_pickle=False)


class PerceptionClient:
    """Blocking stdlib client (call it from a worker thread). Errors raise: a failed perception call makes the
    episode invalid (infrastructure), never a silent baseline step."""

    kind = "http"

    def __init__(self, url: str, timeout: float = 600.0, session: Optional[str] = None) -> None:
        self.url = url.rstrip("/")
        self.timeout = float(timeout)
        self.session = session or f"pcd-{uuid.uuid4().hex}"

    def _post(self, path: str, payload: dict, timeout: Optional[float] = None) -> dict:
        req = urllib.request.Request(self.url + path, data=json.dumps(payload).encode(), method="POST",
                                     headers={"Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=self.timeout if timeout is None else timeout) as resp:
            out = json.loads(resp.read())
        if isinstance(out, dict) and out.get("error"):
            raise RuntimeError(f"perception service {path}: {out['error']}")
        return out

    def health(self) -> dict:
        with urllib.request.urlopen(self.url + "/health", timeout=self.timeout) as resp:
            return json.loads(resp.read())

    def reset(self, instruction: str, parser: Optional[str] = None) -> dict:
        """`parser` is the service's /reset field (service/pcd_perception/server.py:4-5): "simpler" (the authors'
        table) | "libero_goal" (the frozen Setting-B table); sticky per session, so it is sent at every reset."""
        payload = {"session": self.session, "instruction": instruction}
        if parser is not None:
            payload["parser"] = parser
        return self._post("/reset", payload)

    def step(self, image: np.ndarray, instruction: str) -> tuple:
        out = self._post("/step", {"session": self.session, "instruction": instruction, "image_npy": _npy_b64(image)})
        cf = _from_npy_b64(out.pop("cf_npy"))
        return cf, out

    def close(self) -> dict:
        try:
            return self._post("/close", {"session": self.session}, timeout=min(self.timeout, 10.0))
        except Exception as exc:  # noqa: BLE001 - closing is best effort; the episode result is already final
            return {"close_error": f"{type(exc).__name__}: {exc}"}


class StubPerception:
    """Tier 1 only (HarnessStudio's synthetic `fake` benchmark): no models, no network. Deterministic public-frame
    transform with the service's evidence schema: target 'stub object' detected from step 2, cf = frame with the
    centre region shifted by 37 grey levels (so the contrast changes tokens on the fake policy)."""

    kind = "stub"

    def __init__(self, session: Optional[str] = None) -> None:
        self.session = session or f"pcd-stub-{uuid.uuid4().hex}"
        self._step = 0
        self._first = None
        self._present = 0

    def health(self) -> dict:
        return {"ok": True, "version": "stub", "device": "none", "weights": {}, "sam2_C": None}

    def reset(self, instruction: str, parser: Optional[str] = None) -> dict:
        self._step, self._first, self._present = 0, None, 0
        self.parser = parser
        return {"started": True, "instruction": instruction, "targets": ["stub object"], "parser": parser}

    def step(self, image: np.ndarray, instruction: str) -> tuple:
        img = np.asarray(image, dtype=np.uint8)
        h, w = img.shape[:2]
        present = self._step >= 2
        cf = img.copy()
        if present:
            if self._first is None:
                self._first = self._step
            self._present += 1
            ys, xs = slice(h // 4, h - h // 4 or h), slice(w // 4, w - w // 4 or w)
            cf[ys, xs] = ((cf[ys, xs].astype(np.uint16) + 37) % 256).astype(np.uint8)
        ev = {"step": self._step, "phase": "detect" if self._first is None else
              ("first_detection" if self._first == self._step else "track"),
              "targets": ["stub object"],
              "per_target": {"stub object": {"mask_present": present, "area_fraction": 0.25 if present else 0.0,
                                             "tracker_none": False}},
              "robot_mask_present": True, "robot_area_fraction": 0.0, "paste_area_fraction": 0.25 if present else 0.0,
              "inpaint_area_fraction": 0.25 if present else 0.0, "cf_differs": bool((cf != img).any()),
              "timing_ms": {"total_ms": 0.0},
              "episode": {"first_detection_step": self._first, "robot_only_first_detection": False,
                          "targets_never_masked": [] if self._present else ["stub object"],
                          "mask_present_steps": {"stub object": self._present},
                          "tracker_none_steps": {"stub object": []}},
              "calls": {}}
        self._step += 1
        return cf, ev

    def close(self) -> dict:
        return {"closed": self.session}
