"""prr (hs_prr): Pose-Restore-and-Redecide, rtcfpp-20261101 round-6 RECOVERY P1, as a HarnessStudio v2 controller.

Entry points (cards generated by scripts/make_cards.py; every scalar lives in the card's ``params`` block):
- ``prr``        candidate (routes A + B).
- ``prr-hold``   DEVELOPMENT-ONLY control: same trigger/checkpoint/latch/step rules, zero-motion rows.
- ``prr-ortho``  DEVELOPMENT-ONLY norm-matched control: reversal position rows rotated +-90 deg about world z (public
                 coin), PRR rotation law with zero position rows in the correction.
Self-contained: imports no other method package (the RollbackState reversal idea of methods/roboharness is
re-implemented per row, not imported).
"""
from __future__ import annotations

from pathlib import Path

FACTORY = "hs_prr.controller:PRR"
ENTRIES = ("prr", "prr-hold", "prr-ortho")


def _config(card: str):
    from harnessstudio.core.card import config_from_card, load_card
    from harnessstudio.core.method import ModuleRef
    path = Path(__file__).with_name(card)
    params = dict(load_card(path)["params"])
    return config_from_card(path, controller=ModuleRef(FACTORY, params))


def config():
    return _config("paper.yaml")


def config_hold():
    return _config("paper_hold.yaml")


def config_ortho():
    return _config("paper_ortho.yaml")
