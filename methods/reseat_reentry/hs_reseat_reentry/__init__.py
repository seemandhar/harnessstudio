"""reseat-reentry (hs_reseat_reentry): SCALE-decoded frozen OpenVLA + a post-release gap trigger, a codex-pointed and
witnessed remaining instruction object, and an open-gripper re-seat (hover) before SCALE resumes (Run X idea
x-r2-reseat-reentry). See controller.py and README.md.

Entry points (cards generated by scripts/make_cards.py from one constant set; params live in the card):
  reseat-reentry (candidate), reseat-reentry-respondoff (SCALE-shadow null).
"""
from __future__ import annotations

from pathlib import Path

FACTORY = "hs_reseat_reentry.controller:ReseatReentry"


def _config(card_name: str):
    from harnessstudio.core.card import config_from_card, load_card
    from harnessstudio.core.method import ModuleRef

    path = Path(__file__).with_name(card_name)
    params = dict(load_card(path)["params"])
    return config_from_card(path, controller=ModuleRef(FACTORY, params))


def config():
    return _config("paper.yaml")


def config_respondoff():
    return _config("paper_respondoff.yaml")
